export function getLocalizedText(
    value: Record<string, string> | string | undefined | null,
    locale: Locale = 'pl'
): string {
    if (!value) return '';
    if (typeof value === 'string') {
        try {
            const parsed = JSON.parse(value);
            if (typeof parsed === 'object' && parsed !== null) {
                return parsed[locale] || parsed['en'] || parsed['pl'] || Object.values(parsed)[0] || '';
            }
        } catch {
            // Not JSON string, return plain string
        }
        return value;
    }
    return value[locale] || value['en'] || value['pl'] || Object.values(value)[0] || '';
}

export function formatPrice(price: number): string {
    return `${price.toFixed(2)} zł`;
}

export function t(key: keyof typeof translations.pl | string, locale: Locale = 'pl', params?: Record<string, string | number>): string {
    const dict = translations[locale] || translations.pl;
    let text = (dict as any)[key] || (translations.pl as any)[key] || key;

    if (typeof text !== 'string') {
        return text;
    }

    if (params) {
        Object.entries(params).forEach(([paramKey, paramVal]) => {
            text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
        });
    }

    return text;
}
